  if (typeof document === 'undefined' || typeof window === 'undefined') return;

  var CONFIG = window.ASKBOT_CONFIG || {};
  var LOGO = CONFIG.logoPath || 'assets/club-avatar.png';
  var DEFAULT_FACTS = { total: 45, levels: 5, c: [10, 11, 11, 8, 5] };
  var WELCOME = 'مرحبًا بك في أكاديمية الروبوتيك والذكاء الاصطناعي.\nأنا «اسألني»، مساعدك داخل المنصة: أجيب عن أسئلتك حول الدروس والمستويات، والتسجيل والحساب، والشهادات، والنادي.\nلا تشارك معلوماتك الشخصية هنا، واسألني ما شئت عن الأكاديمية.';
  var HOME_CHIPS = ['ما هي المسارات المتوفرة؟', 'كم عدد الدروس؟', 'هل الدورة مجانية؟', 'كيف أنشئ حسابًا؟', 'كيف أحصل على الشهادة؟', 'من هو المشرف على الأكاديمية؟'];
  var ROBOT_SVG = '<svg viewBox="0 0 48 48" fill="none" aria-hidden="true"><rect x="10" y="14" width="28" height="22" rx="6" fill="#10355F"/><circle cx="19" cy="25" r="3.2" fill="#22C3E6"/><circle cx="29" cy="25" r="3.2" fill="#22C3E6"/><rect x="18" y="31" width="12" height="2.6" rx="1.3" fill="#EEF4F9"/><path d="M24 14V8" stroke="#10355F" stroke-width="2.6" stroke-linecap="round"/><circle cx="24" cy="6.5" r="2.6" fill="#22C3E6"/><rect x="5" y="20" width="4" height="9" rx="2" fill="#0A2242"/><rect x="39" y="20" width="4" height="9" rx="2" fill="#0A2242"/></svg>';

  function computeFacts() {
    try {
      var D = window.ACADEMY_DATA;
      if (D && D.levels && D.lessons && D.lessons.length) {
        var c = [0, 0, 0, 0, 0];
        D.lessons.forEach(function (l) { if (l.level >= 1 && l.level <= 5) c[l.level - 1]++; });
        return { total: D.lessons.length, levels: D.levels.length, c: c };
      }
    } catch (e) { /* تجاهل: نعود إلى القيم الافتراضية */ }
    return DEFAULT_FACTS;
  }

  function esc(s) {
    return String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
      .replace(/"/g, '&quot;').replace(/'/g, '&#39;');
  }

  var state = { open: false, welcomed: false, ctx: {}, facts: computeFacts() };
  var els = {};

  function avatarHTML(cls) {
    return '<span class="askbot-avatar ' + (cls || '') + '"><img src="' + esc(LOGO) + '" alt="" onerror="this.parentNode.innerHTML=window.__ASKBOT_SVG">' +
      '</span>';
  }
  window.__ASKBOT_SVG = ROBOT_SVG;

